updated = 0
for filename, extra_lines in expansions.items():
    filepath = os.path.join(DOCS, filename)
    if not os.path.exists(filepath):
        print(f"SKIP: {filename} not found")
        continue
    with open(filepath, 'r') as f:
        content = f.read()
    
    # Find the "## 玩法规则" section and add extra lines before "## 核心循环"
    # Or find a good insertion point
    lines = content.split('\n')
    
    # Insert before "## 核心循环"
    insert_idx = None
    for i, line in enumerate(lines):
        if line.strip() == "## 核心循环":
            insert_idx = i
            break
    
    if insert_idx:
        for el in extra_lines:
            lines.insert(insert_idx, el)
            insert_idx += 1
        
        with open(filepath, 'w') as f:
            f.write('\n'.join(lines))
        
        new_count = len(lines)
        print(f"Updated {filename}: now {new_count} lines (+{len(extra_lines)})")
        updated += 1
    else:
        print(f"ERROR: Could not find insert point in {filename}")

print(f"\nTotal updated: {updated}")

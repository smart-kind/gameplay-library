def main():
    # Search 3 groups via iTunes API
    groups = [
        ("puzzle platformer casual mobile", []),
        ("card game casual strategy mobile", []),
        ("word game casual brain training", []),
    ]
    
    all_games = []
    for term, _ in groups:
        results = itunes_search(term)
        for r in results:
            name = r.get("trackName", "")
            desc = r.get("description", "")
            dev = r.get("artistName", "Unknown")
            genres = r.get("genres", [])
            tid = r.get("trackId", "N/A")
            if name and name not in [g[0] for g in all_games]:
                all_games.append((name, desc, dev, str(genres), str(tid), term))
        time.sleep(3)
    
    print(f"Found {len(all_games)} unique games")
    
    docs_created = []
    for name, desc, dev, genres, tid, source in all_games:
        if not name or not desc:
            continue
        filename, content = generate_doc(name, desc, source, tid, dev, genres)
        filepath = os.path.join(DOCS, filename)
        with open(filepath, 'w') as f:
            f.write(content)
        docs_created.append((name, filename))
        print(f"  Created: {filename} ({len(content.splitlines())} lines)")
        time.sleep(0.1)
    
    print(f"\nTotal docs created: {len(docs_created)}")
    # Output for parsing
    for name, fn in docs_created:
        print(f"DOC:{name}:{fn}")

if __name__ == "__main__":
    main()
